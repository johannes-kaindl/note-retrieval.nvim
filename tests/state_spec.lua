local T = require('note_retrieval.kit.test')
local state = require('note_retrieval.state')

-- Every case starts without a state file.
local function fresh()
  vim.fn.delete(vim.fn.fnamemodify(state.path(), ':h'), 'rf')
end

T.case('state: the file lives in stdpath("state")/note-retrieval/state.json', function()
  T.eq(state.path(), vim.fn.stdpath('state') .. '/note-retrieval/state.json')
end)

T.case('state: a model is remembered per endpoint URL and read back', function()
  fresh()
  T.eq(state.model('http://a'), nil)
  state.set_model('http://a', 'm1')
  state.set_model('http://b', 'm2')
  state.set_model('http://a', 'm3')
  T.eq(state.model('http://a'), 'm3')
  T.eq(state.model('http://b'), 'm2')
  T.eq(state.model('http://c'), nil)
  local f = assert(io.open(state.path(), 'rb'))
  local saved = vim.json.decode(f:read('*a'))
  f:close()
  T.eq(saved, { models = { ['http://a'] = 'm3', ['http://b'] = 'm2' } })
end)

T.case('state: a broken file reads as nothing and is replaced by the next write', function()
  fresh()
  vim.fn.mkdir(vim.fn.fnamemodify(state.path(), ':h'), 'p')
  local f = assert(io.open(state.path(), 'wb'))
  f:write('{ not json')
  f:close()
  T.eq(state.model('http://a'), nil)
  state.set_model('http://a', 'm1')
  T.eq(state.model('http://a'), 'm1')
end)

T.case('state: a file of another shape ({"models": []}) is not read and does not stop a write', function()
  fresh()
  vim.fn.mkdir(vim.fn.fnamemodify(state.path(), ':h'), 'p')
  local f = assert(io.open(state.path(), 'wb'))
  f:write('{"models":["x"]}')
  f:close()
  T.eq(state.model('http://a'), nil)
  state.set_model('http://a', 'm1')
  T.eq(state.model('http://a'), 'm1')
end)

T.case('state: a remembered entry that is no string is not a model', function()
  fresh()
  vim.fn.mkdir(vim.fn.fnamemodify(state.path(), ':h'), 'p')
  local f = assert(io.open(state.path(), 'wb'))
  f:write('{"models":{"http://a":5,"http://b":"m"}}')
  f:close()
  T.eq(state.model('http://a'), nil)
  T.eq(state.model('http://b'), 'm')
end)
